#!/usr/bin/env node
// Turns data/catalog.json into supabase/seed.sql.
//
//   node scripts/catalog-to-sql.mjs
//
// The SQL upserts by slug / sku / code, so it can be run again on a live
// database (e.g. right before launch) to refresh stock and prices without
// duplicating anything.

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const catalog = JSON.parse(await readFile(path.join(ROOT, "data/catalog.json"), "utf8"));
const OUT = path.join(ROOT, "supabase/seed.sql");

const q = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (v == null ? "null" : String(Number(v)));
const textArr = (a) => (a.length ? `array[${a.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const intArr = (a) => (a.length ? `array[${a.map(num).join(", ")}]::bigint[]` : "'{}'::bigint[]");
const json = (o) => `${q(JSON.stringify(o))}::jsonb`;

const out = [
  `-- Generated by scripts/catalog-to-sql.mjs from data/catalog.json`,
  `-- Source: ${catalog.source.url}, fetched ${catalog.source.fetched_at}`,
  `-- Do not edit by hand; re-run the script instead.`,
  ``,
  `begin;`,
  ``,
];

catalog.currencies.forEach((c, i) => {
  out.push(
    `insert into public.currencies (code, symbol, ngn_per_unit, position) values (${q(c.code)}, ${q(c.symbol)}, ${num(c.rate)}, ${i})`,
    `  on conflict (code) do update set symbol = excluded.symbol, ngn_per_unit = excluded.ngn_per_unit, position = excluded.position;`,
  );
});
out.push("");

for (const p of catalog.products) {
  out.push(
    `-- ${p.name}`,
    `insert into public.products (slug, name, category, description, dimensions, option_names, images, position, legacy_bumpa_ids, legacy_paths)`,
    `values (${q(p.slug)}, ${q(p.name)}, ${q(p.category)}, ${q(p.description)}, ${q(p.dimensions)}, ${textArr(p.option_names)}, ${textArr(p.images)}, ${p.position}, ${intArr(p.legacy.bumpa_ids)}, ${textArr(p.legacy.bumpa_urls)})`,
    `on conflict (slug) do update set name = excluded.name, category = excluded.category, description = excluded.description,`,
    `  dimensions = excluded.dimensions, option_names = excluded.option_names, images = excluded.images, position = excluded.position,`,
    `  legacy_bumpa_ids = excluded.legacy_bumpa_ids, legacy_paths = excluded.legacy_paths;`,
  );
  p.variants.forEach((v, i) => {
    out.push(
      `insert into public.product_variants (product_id, sku, options, swatch, price_ngn, compare_at_ngn, stock, images, has_photo, position, legacy_bumpa_product_id, legacy_bumpa_variant_id)`,
      `select id, ${q(v.sku)}, ${json(v.options)}, ${q(v.swatch)}, ${num(v.price_ngn)}, ${num(v.compare_at_ngn)}, ${num(v.stock)}, ${textArr(v.images)}, ${v.has_photo}, ${i}, ${num(v.legacy.bumpa_product_id)}, ${num(v.legacy.bumpa_variant_id)}`,
      `from public.products where slug = ${q(p.slug)}`,
      `on conflict (sku) do update set options = excluded.options, swatch = excluded.swatch, price_ngn = excluded.price_ngn,`,
      `  compare_at_ngn = excluded.compare_at_ngn, stock = excluded.stock, images = excluded.images, has_photo = excluded.has_photo, position = excluded.position;`,
    );
  });
  out.push("");
}

catalog.collections.forEach((c, i) => {
  out.push(
    `insert into public.collections (slug, name, description, image, position) values (${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${q(c.image)}, ${i})`,
    `  on conflict (slug) do update set name = excluded.name, description = excluded.description, image = excluded.image, position = excluded.position;`,
  );
  c.products.forEach((slug, j) => {
    out.push(
      `insert into public.collection_products (collection_id, product_id, position)`,
      `select c.id, p.id, ${j} from public.collections c, public.products p where c.slug = ${q(c.slug)} and p.slug = ${q(slug)}`,
      `  on conflict (collection_id, product_id) do update set position = excluded.position;`,
    );
  });
});

out.push("", "commit;", "");

await mkdir(path.dirname(OUT), { recursive: true });
await writeFile(OUT, out.join("\n"));
console.log(`Wrote ${path.relative(ROOT, OUT)}`);
